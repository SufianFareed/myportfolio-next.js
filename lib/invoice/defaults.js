export function nextInvoiceNumber(history, prefix, dateISO, extraNumbers = []) {
  const safePrefix = (prefix || "INV").trim().replace(/[^A-Za-z0-9]/g, "").toUpperCase() || "INV";
  const year = (dateISO || todayISO()).slice(0, 4);
  const re = new RegExp(`^${safePrefix}-${year}-(\\d+)$`, "i");
  const numbers = [...history.map((inv) => inv.number), ...extraNumbers];
  let max = 0;
  for (const number of numbers) {
    const match = re.exec(String(number || "").trim());
    if (match) max = Math.max(max, parseInt(match[1], 10));
  }
  return `${safePrefix}-${year}-${String(max + 1).padStart(3, "0")}`;
}

export function blankInvoice(profile, history = [], extraNumbers = []) {
  const today = todayISO();
  const now = new Date().toISOString();
  return {
    id: newId(),
    number: nextInvoiceNumber(history, profile.invoicePrefix, today, extraNumbers),
    issueDate: today,
    dueDate: addDaysISO(today, 14),
    status: "Draft",
    currency: profile.currency,
    poNumber: "",
    client: emptyClient(),
    items: [blankItem()],
    discountPct: "",
    discountFixed: "",
    taxPct: "",
    fees: "",
    amountPaid: "",
    notes: "",
    terms: DEFAULT_TERMS,
    thankYou: DEFAULT_THANK_YOU,
    createdAt: now,
    updatedAt: now,
  };
}

