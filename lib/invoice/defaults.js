export function duplicateInvoice(invoice, profile, history) {
  const today = todayISO();
  const span = Math.max(0, diffDaysISO(invoice.issueDate, invoice.dueDate)) || 14;
  const now = new Date().toISOString();
  return {
    ...invoice,
    id: newId(),
    number: nextInvoiceNumber(history, profile.invoicePrefix, today, [invoice.number]),
    issueDate: today,
    dueDate: addDaysISO(today, span),
    status: "Draft",
    amountPaid: "",
    client: { ...invoice.client },
    items: invoice.items.map((item) => ({ ...item, id: newId() })),
    createdAt: now,
    updatedAt: now,
  };
}

const str = (v, fallback = "") => (typeof v === "string" ? v : v == null ? fallback : String(v));

export function sanitizeProfile(raw) {
  const base = defaultProfile();
  if (!raw || typeof raw !== "object") return base;
  const logo =
    raw.logo && typeof raw.logo.dataUrl === "string" && raw.logo.dataUrl.startsWith("data:image/")
      ? { dataUrl: raw.logo.dataUrl, w: Number(raw.logo.w) || 1, h: Number(raw.logo.h) || 1 }
      : null;
  const pay = raw.payment && typeof raw.payment === "object" ? raw.payment : {};
  return {
    name: str(raw.name, base.name),
    profession: str(raw.profession, base.profession),
    email: str(raw.email),
    phone: str(raw.phone),
    address: str(raw.address),
    website: str(raw.website),
    taxId: str(raw.taxId),
    country: str(raw.country, base.country),
    invoicePrefix: str(raw.invoicePrefix, base.invoicePrefix),
    currency: CURRENCIES.includes(raw.currency) ? raw.currency : base.currency,
    logo,
    payment: {
      bankName: str(pay.bankName),
      accountTitle: str(pay.accountTitle),
      accountNumber: str(pay.accountNumber),
      iban: str(pay.iban),
      wallet: str(pay.wallet),
      custom: str(pay.custom),
    },
    template: TEMPLATES.some((t) => t.id === raw.template) ? raw.template : base.template,
    accent: /^#[0-9a-f]{6}$/i.test(raw.accent || "") ? raw.accent : base.accent,
  };
}

export function sanitizeInvoice(raw, profile) {
  const base = blankInvoice(profile);
  if (!raw || typeof raw !== "object") return base;
  const client = raw.client && typeof raw.client === "object" ? raw.client : {};
  const items =
    Array.isArray(raw.items) && raw.items.length
      ? raw.items.map((item) => ({
          id: str(item && item.id) || newId(),
          description: str(item && item.description),
          qty: str(item && item.qty, "1"),
          price: str(item && item.price),
          discountPct: str(item && item.discountPct),
        }))
      : [blankItem()];
  return {
    id: str(raw.id) || base.id,
    number: str(raw.number, base.number),
    issueDate: str(raw.issueDate, base.issueDate),
    dueDate: str(raw.dueDate, base.dueDate),
    status: STATUSES.includes(raw.status) ? raw.status : "Draft",
    currency: CURRENCIES.includes(raw.currency) ? raw.currency : profile.currency,
    poNumber: str(raw.poNumber),
    client: {
      name: str(client.name),
      company: str(client.company),
      email: str(client.email),
      phone: str(client.phone),
      address: str(client.address),
      website: str(client.website),
    },
    items,
    discountPct: str(raw.discountPct),
    discountFixed: str(raw.discountFixed),
    taxPct: str(raw.taxPct),
    fees: str(raw.fees),
    amountPaid: str(raw.amountPaid),
    notes: str(raw.notes),
    terms: str(raw.terms),
    thankYou: str(raw.thankYou),
    createdAt: str(raw.createdAt, base.createdAt),
    updatedAt: str(raw.updatedAt, base.updatedAt),
  };
}

export function sanitizeHistory(raw, profile) {
  if (!Array.isArray(raw)) return [];
  return raw.filter((x) => x && typeof x === "object").map((x) => sanitizeInvoice(x, profile));
}

// Used to tell whether the form differs from what was last saved.
function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical);
  if (value && typeof value === "object") {
    return Object.keys(value).sort().reduce((out, key) => {
      out[key] = canonical(value[key]);
      return out;
    }, {});
  }
  return value;
}

export function stableKey(invoice) {
  const { createdAt, updatedAt, ...rest } = invoice; // eslint-disable-line no-unused-vars
  return JSON.stringify(canonical(rest));
}
